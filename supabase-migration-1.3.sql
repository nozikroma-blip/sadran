-- Обновление базы до версии приложения 1.3.0: номера и названия проектов
-- не должны повторяться. Выполнить в Supabase: SQL Editor -> New query -> Run.
-- Скрипт безопасно запускать повторно.

-- Проверка на стороне приложения ловит совпадения сразу и с понятным текстом,
-- но её недостаточно: двое участников могут нажать «Сохранить» одновременно,
-- и каждый увидит список без проекта другого. Последнее слово — за базой.

-- Сравниваем без учёта регистра и лишних пробелов по краям:
-- «Савьон», «савьон» и « Савьон » считаются одним и тем же названием.
create unique index if not exists projects_name_uniq
  on public.projects (lower(btrim(name)));

-- Пустой номер не участвует в проверке — проектов без номера может быть много.
create unique index if not exists projects_code_uniq
  on public.projects (lower(btrim(code)))
  where btrim(code) <> '';

